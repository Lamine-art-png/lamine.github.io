"""Bounded, deterministic decisions for TEST-only Platform API applications.

No LIVE approvals, provider writes, physical execution, customer messages or
secrets are generated by this process. Decisions and entitlements are audited.
"""
from __future__ import annotations

from datetime import datetime, timedelta

from sqlalchemy.orm import Session

from app.core.config import settings
from app.core.organization_access import organization_access_allowed
from app.models.platform_product import PlatformApiApplication, PlatformProgramEnrollment
from app.models.saas import Organization, OrganizationMembership, User
from app.models.platform_api import PlatformApiKey
from app.platform_api.product_audit import record_product_audit

PENDING = ("submitted", "under_review")
PROGRAM = "developer_private_beta"
TEST_SCOPES = (
    "projects:read", "fields:read", "sources:read", "observations:read",
    "recommendations:read", "reports:read", "jobs:read", "usage:read",
    "request_logs:read",
)


def _decision(db: Session, app: PlatformApiApplication) -> tuple[bool, str]:
    if app.application_type != "developer_beta" or app.requested_environment != "test":
        return False, "Automated access is restricted to the synthetic-data TEST developer beta. LIVE and partner privileges are not granted."
    org = db.get(Organization, app.organization_id)
    user = db.get(User, app.applicant_user_id)
    if org is None or user is None or not organization_access_allowed(org):
        return False, "Organization verification or applicant identity is not eligible for TEST access."
    if not user.is_active or user.account_status != "active" or user.access_restricted_at is not None:
        return False, "Applicant account is inactive or restricted."
    if user.locked_until is not None and user.locked_until > datetime.utcnow():
        return False, "Applicant account is temporarily locked."
    if user.email_verification_status != "verified" or user.email_verified_at is None:
        return False, "A verified applicant email is required."
    if user.email.strip().lower() != str(app.corporate_email or "").strip().lower():
        return False, "Applicant email and submitted corporate email do not match."
    member = db.query(OrganizationMembership).filter(
        OrganizationMembership.organization_id == org.id,
        OrganizationMembership.user_id == user.id,
        OrganizationMembership.status == "active",
        OrganizationMembership.role.in_(("owner", "admin")),
    ).first()
    if member is None:
        return False, "An active organization owner or administrator must apply."
    # An abuse suspension is never silently lifted, including one associated
    # with a different enrollment program.
    suspended = db.query(PlatformProgramEnrollment).filter(
        PlatformProgramEnrollment.organization_id == org.id,
        PlatformProgramEnrollment.status == "suspended",
    ).first()
    if suspended is not None:
        return False, "Existing Platform API suspension blocks automatic enrollment."
    # No provider or physical scopes are granted even if an application asks
    # for them. This decision only provides a synthetic TEST surface.
    keys = db.query(PlatformApiKey).filter(PlatformApiKey.organization_id == org.id, PlatformApiKey.environment == "test", PlatformApiKey.status == "active").all()
    if any(not set(key.scopes or []).issubset(TEST_SCOPES) for key in keys):
        return False, "Existing TEST credentials exceed the permitted scope set."
    if bool(getattr(settings, "PLATFORM_API_TERMS_ENFORCEMENT_ENABLED", False)):
        from fastapi import HTTPException
        from app.platform_api.terms import require_user_acceptance
        try:
            require_user_acceptance(db, organization_id=org.id, user_id=user.id)
        except HTTPException:
            return False, "Current developer agreements must be accepted before TEST access is available."
    return True, "Verified organization owner approved for bounded synthetic-data TEST API access."


def adjudicate_submitted_test_applications(
    db: Session, *, organization_id: str | None = None, limit: int = 200,
) -> int:
    """Resolve outstanding applications without granting elevated privileges.

    Feature flag defaults OFF; deployments must explicitly activate it.
    All changes, including an enrollment and its decision, commit atomically.
    No outbound email or API key is created.
    """
    if not bool(getattr(settings, "PLATFORM_API_AUTOMATED_TEST_REVIEWS_ENABLED", False)):
        return 0
    query = db.query(PlatformApiApplication).filter(
        PlatformApiApplication.status.in_(PENDING),
        PlatformApiApplication.application_type == "developer_beta",
    )
    if organization_id is not None:
        query = query.filter(PlatformApiApplication.organization_id == organization_id)
    rows = query.order_by(PlatformApiApplication.created_at.asc()).limit(max(1, min(limit, 500))).with_for_update(skip_locked=True).all()
    processed = 0
    for app in rows:
        allowed, reason = _decision(db, app)
        if allowed:
            enrollment = db.query(PlatformProgramEnrollment).filter(
                PlatformProgramEnrollment.organization_id == app.organization_id,
                PlatformProgramEnrollment.program == PROGRAM,
            ).with_for_update().first()
            # A previously suspended / revoked row is never reactivated.
            if enrollment is not None and enrollment.status not in ("active", "approved"):
                allowed, reason = False, "An existing inactive developer enrollment prevents automatic reactivation."
            elif enrollment is not None and "live" in (enrollment.allowed_environments_json or []):
                allowed, reason = False, "Existing broader entitlement cannot be relabelled as automatically approved TEST-only access."
            else:
                if enrollment is None:
                    enrollment = PlatformProgramEnrollment(
                        organization_id=app.organization_id,
                        application_id=app.id,
                        program=PROGRAM,
                        status="active",
                        allowed_environments_json=["test"],
                        maximum_projects=1,
                        maximum_live_projects=0,
                        maximum_service_accounts=2,
                        maximum_keys=2,
                        maximum_webhooks=0,
                        default_scopes_json=list(TEST_SCOPES),
                        provider_restrictions_json={},
                        resource_restrictions_json={},
                        rate_limit_policy_json={},
                        quota_policy_json={},
                        billing_mode="none",
                        plan_identifier="sandbox",
                        support_tier="documentation",
                        approved_at=datetime.utcnow(),
                        effective_at=datetime.utcnow(),
                        expires_at=datetime.utcnow() + timedelta(days=90),
                    )
                    db.add(enrollment)
        app.status = "approved" if allowed else "rejected"
        app.decided_at = datetime.utcnow()
        app.decision_reason = reason
        app.assigned_reviewer_user_id = None
        record_product_audit(
            db,
            event_type="platform.application.auto_approved" if allowed else "platform.application.auto_rejected",
            subject_type="application",
            subject_id=app.id,
            organization_id=app.organization_id,
            actor_type="system",
            reason=reason,
            metadata={"decision_engine": "bounded_test_v1", "environment": "test" if allowed else "none"},
        )
        processed += 1
    if processed:
        db.commit()
    return processed
