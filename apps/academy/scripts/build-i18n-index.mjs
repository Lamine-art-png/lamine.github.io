// Regenerates src/i18n/index.js from the catalogs present in src/i18n/.
// Run after adding or removing a locale catalog: node scripts/build-i18n-index.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "../src/i18n");
const files = readdirSync(dir).filter((f) => f.endsWith(".json") && !f.startsWith("_")).sort();
const meta = JSON.parse(readFileSync(join(dir, "_meta.json"), "utf8"));
const ident = (code) => `L_${code.replace(/[^A-Za-z0-9]/g, "_")}`;
const lines = [
  "// Generated by scripts/build-i18n-index.mjs — do not edit by hand.",
  ...files.map((f) => `import ${ident(f.replace(/\.json$/, ""))} from "./${f}" with { type: "json" };`),
  "",
  "export const CATALOGS = {",
  ...files.map((f) => `  ${JSON.stringify(f.replace(/\.json$/, ""))}: ${ident(f.replace(/\.json$/, ""))},`),
  "};",
  "",
  `export const CATALOG_META = ${JSON.stringify(meta, null, 2)};`,
  "",
];
writeFileSync(join(dir, "index.js"), lines.join("\n"));
console.log(`Indexed ${files.length} catalogs: ${files.map((f) => f.replace(".json", "")).join(", ")}`);
