// Generates migrations/0002_curriculum_seed.sql (and its down migration) from
// src/content. Re-run after editing seed content *before* the migration has
// been applied anywhere; once applied, make further content changes through
// the admin console or a new migration.
//
//   node scripts/generate-seed.mjs
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { PROGRAMS, INSTRUCTORS, COURSE_RECORDS, PATHS } from "../src/content/catalog.js";
import { A1 } from "../src/content/courses/a1.js";

const FULL = [A1];
const TS = "2026-10-17T00:00:00.000Z";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const q = (v) => (v == null ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const insert = (table, row) => `INSERT INTO ${table} (${Object.keys(row).join(", ")}) VALUES (${Object.values(row).map(q).join(", ")});`;
const out = [];
const down = [];
const L = (s) => out.push(s);

L("-- AGRO-AI Academy curriculum seed. Generated by scripts/generate-seed.mjs — do not edit by hand.");
L("-- Reverse with migrations/down/0002_curriculum_seed.down.sql.");
L("");

for (const [i, p] of PROGRAMS.entries()) {
  L(insert("programs", { id: p.id, slug: p.slug, code: p.code, title: p.title, summary: p.summary, description: p.summary, sort_order: i + 1, status: "published", created_at: TS, updated_at: TS }));
  down.push(`DELETE FROM programs WHERE id = ${q(p.id)};`);
}
for (const ins of INSTRUCTORS) {
  L(insert("instructors", { id: ins.id, slug: ins.slug, name: ins.name, title: ins.title, bio: ins.bio, is_ai_avatar: ins.is_ai_avatar || 0, disclosure: ins.disclosure || null, sort_order: ins.sort, status: ins.status, created_at: TS, updated_at: TS }));
  down.push(`DELETE FROM instructors WHERE id = ${q(ins.id)};`);
}

const fullById = new Map(FULL.map((f) => [f.id, f]));
for (const c of COURSE_RECORDS) {
  const full = fullById.get(c.id);
  L(
    insert("courses", {
      id: c.id,
      slug: c.slug,
      program_id: c.program,
      title: c.title,
      subtitle: c.subtitle,
      description: full?.description ?? `${c.subtitle}\n\nThis course is part of the AGRO-AI Academy roadmap and is in preparation.`,
      level: c.level,
      duration_minutes: c.minutes,
      source_locale: "en",
      objectives_json: JSON.stringify(full?.objectives ?? []),
      audience_json: JSON.stringify(c.audience || []),
      topics_json: JSON.stringify(c.topics || []),
      prerequisites_text: full?.prerequisites_text ?? "",
      status: full?.status ?? c.status,
      planned_release_date: full?.planned_release_date ?? null,
      certificate_enabled: 1,
      passing_score: 80,
      require_all_lessons: 1,
      require_quizzes_pass: 0,
      sort_order: c.sort,
      content_review_note: full?.content_review_note ?? "Instruction not yet written.",
      created_at: TS,
      updated_at: TS,
    }),
  );
  L(insert("course_instructors", { course_id: c.id, instructor_id: "ins_faculty", sort_order: 0 }));
}
down.unshift(`DELETE FROM courses WHERE id IN (${COURSE_RECORDS.map((c) => q(c.id)).join(", ")});`);
L(insert("course_prerequisites", { course_id: "crs_a3", prerequisite_course_id: "crs_a1", is_required: 0 }));
L(insert("course_prerequisites", { course_id: "crs_a4", prerequisite_course_id: "crs_a1", is_required: 0 }));
L(insert("course_prerequisites", { course_id: "crs_d1", prerequisite_course_id: "crs_a1", is_required: 0 }));

for (const [i, p] of PATHS.entries()) {
  L(insert("learning_paths", { id: p.id, slug: p.slug, title: p.title, role: p.role, summary: p.summary, sort_order: i + 1, status: "published", created_at: TS, updated_at: TS }));
  p.courses.forEach((cid, j) => L(insert("learning_path_courses", { path_id: p.id, course_id: cid, sort_order: j })));
  down.unshift(`DELETE FROM learning_paths WHERE id = ${q(p.id)};`);
}

let qCount = 0;
for (const course of FULL) {
  L("");
  L(`-- Full course: ${course.id}`);
  L(`UPDATE course_instructors SET sort_order = 0 WHERE course_id = ${q(course.id)};`);
  // Assessments first (lessons reference them).
  for (const a of course.assessments) {
    L(
      insert("assessments", {
        id: a.id,
        course_id: course.id,
        kind: a.kind,
        title: a.title,
        instructions: a.instructions || "",
        time_limit_seconds: a.timeLimit ?? null,
        passing_score: a.passing,
        max_attempts: a.maxAttempts ?? null,
        cooldown_minutes: a.cooldown ?? 0,
        shuffle_questions: 1,
        shuffle_options: 1,
        feedback_policy: a.feedback,
        is_certification: a.certification ? 1 : 0,
        is_required: 1,
        status: "active",
        created_at: TS,
        updated_at: TS,
      }),
    );
  }
  let lessonOrder = 0;
  for (const [mi, m] of course.modules.entries()) {
    L(insert("modules", { id: m.id, course_id: course.id, title: m.title, summary: m.summary || "", sort_order: mi + 1, created_at: TS, updated_at: TS }));
    for (const les of m.lessons) {
      let videoId = null;
      if (les.script) {
        videoId = `vid_${les.id.slice(4)}`;
        L(insert("video_assets", { id: videoId, title: `${course.id.toUpperCase()} · ${les.title}`, provider: "synthesia", status: "scripted", instructor_id: "ins_joshua", script_md: les.script, created_at: TS, updated_at: TS }));
      }
      L(
        insert("lessons", {
          id: les.id,
          course_id: course.id,
          module_id: m.id,
          slug: les.slug,
          title: les.title,
          type: les.type,
          summary: les.summary || "",
          body_md: les.body,
          interactive_json: les.interactive ? JSON.stringify(les.interactive) : null,
          est_minutes: les.minutes,
          video_id: videoId,
          assessment_id: les.assessment || null,
          is_required: 1,
          is_preview: les.preview ? 1 : 0,
          sort_order: ++lessonOrder,
          status: "ready",
          created_at: TS,
          updated_at: TS,
        }),
      );
    }
  }
  for (const b of course.banks) {
    L(insert("question_banks", { id: b.id, course_id: course.id, title: b.title, description: "", created_at: TS, updated_at: TS }));
    for (const k of b.cases || []) L(insert("question_cases", { id: k.id, bank_id: b.id, title: k.title, body_md: k.body, created_at: TS }));
    for (const qu of b.questions) {
      const type = qu.type === "case" ? qu.baseType : qu.type;
      let data = {};
      let answer = {};
      let n = 0;
      const id = () => `o${++n}`;
      if (type === "single" || type === "multiple") {
        const opts = qu.options.map(([text, ok]) => ({ id: id(), text, ok }));
        data = { options: opts.map(({ id: i, text }) => ({ id: i, text })) };
        answer = { correct: opts.filter((o) => o.ok).map((o) => o.id) };
        if (type === "single" && answer.correct.length !== 1) throw new Error(`${qu.id}: single needs one correct option`);
      } else if (type === "true_false") {
        answer = { value: qu.answer === true };
      } else if (type === "matching") {
        const left = qu.pairs.map(([l]) => ({ id: `l${++n}`, text: l }));
        const right = qu.pairs.map(([, r]) => ({ id: `r${++n}`, text: r }));
        data = { left, right };
        answer = { pairs: Object.fromEntries(left.map((l, i) => [l.id, right[i].id])) };
      } else if (type === "ordering") {
        const items = qu.order.map((text) => ({ id: id(), text }));
        data = { items };
        answer = { order: items.map((i) => i.id) };
      } else if (type === "short_answer") {
        data = { max_length: 120 };
        answer = { accepted: qu.accepted, match: "exact" };
      } else throw new Error(`${qu.id}: unknown type ${type}`);
      L(
        insert("questions", {
          id: qu.id,
          bank_id: b.id,
          case_id: qu.case || null,
          lesson_id: qu.lesson || null,
          type,
          difficulty: qu.difficulty,
          prompt: qu.prompt,
          data_json: JSON.stringify(data),
          answer_json: JSON.stringify(answer),
          explanation: qu.explanation || "",
          grading: "auto",
          points: 1,
          status: "active",
          created_at: TS,
          updated_at: TS,
        }),
      );
      qCount++;
    }
  }
  for (const a of course.assessments) {
    a.rules.forEach((r, i) => L(insert("assessment_rules", { id: `rul_${a.id.slice(4)}_${i + 1}`, assessment_id: a.id, bank_id: r.bank, difficulty: r.difficulty || null, draw_count: r.count, sort_order: i + 1 })));
  }
  down.unshift(`DELETE FROM video_assets WHERE id LIKE 'vid_a1_%';`);
  down.unshift(`DELETE FROM question_banks WHERE course_id = ${q(course.id)};`);
}

writeFileSync(join(root, "migrations/0002_curriculum_seed.sql"), out.join("\n") + "\n");
writeFileSync(
  join(root, "migrations/down/0002_curriculum_seed.down.sql"),
  ["-- Reverses 0002_curriculum_seed.sql. Learner records tied to these courses are deleted by cascade; export first.", ...down].join("\n") + "\n",
);
console.log(`Seed: ${PROGRAMS.length} programs, ${COURSE_RECORDS.length} courses (${FULL.length} with full instruction), ${PATHS.length} paths, ${qCount} questions.`);
